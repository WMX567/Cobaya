"""Generate Planck, ACT, and joint evaluate/minimize/MCMC/PolyChord input files."""

from pathlib import Path

import yaml


def make_configs():
    folder = Path(__file__).with_name("configs")
    folder.mkdir(exist_ok=True)
    # Priors follow the current CosmoCLASS/lhs_sampling.py training domain.
    specification = {
        "omega_b": (0.015, 0.03, 0.02237, 0.0001),
        "omega_cdm": (0.09, 0.15, 0.12, 0.001),
        "h": (0.4, 1.0, 0.674, 0.005),
        "tau_reio": (0.02, 0.20, 0.0544, 0.005),
        "n_s": (0.85, 1.05, 0.965, 0.004),
        "m_ncdm": (0.0001, 1.5, 0.06, 0.02),
        "ln_A_s_1e10": (2.5, 3.5, 3.044, 0.01),
        "N_ur": (1.0, 4.0, 2.0328, 0.05),
        "log10_G_eff_nu": (-7.0, -0.5, -5.0, 0.1),
    }
    planck_low = {"planck_2018_lowl.TT": None, "planck_2018_lowl.EE_sroll2": None}
    combinations = {
        "planck": {"planck_2018_highl_plik.TTTEEE_lite_native": None, **planck_low},
        "act": {"emulator_bridge.act.ACTDR6": None},
        "act_planck": {"emulator_bridge.act.ACTDR6": None,
                       "act_dr6_cmbonly.PlanckActCut": None, **planck_low},
    }
    for dataset, likelihood in combinations.items():
        parameters = {key: {"prior": {"min": lo, "max": hi}, "ref": ref,
                            "proposal": proposal}
                      for key, (lo, hi, ref, proposal) in specification.items()}
        if dataset != "act":
            parameters["A_planck"] = {"prior": {"dist": "norm", "loc": 1.0, "scale": 0.0025},
                                      "ref": 1.0, "proposal": 0.0005}
        if dataset != "planck":
            parameters["A_act"] = {"prior": {"min": 0.5, "max": 1.5}, "ref": 1.0, "proposal": 0.003}
            parameters["P_act"] = {"prior": {"min": 0.9, "max": 1.1}, "ref": 1.0, "proposal": 0.003}
        for mode in ("evaluate", "minimize", "mcmc", "polychord"):
            sampler = {"evaluate": {"N": 1}} if mode == "evaluate" else (
                {"minimize": {"method": "bobyqa", "best_of": 1, "max_evals": 500,
                              "seed": 42}} if mode == "minimize" else
                {"mcmc": {"burn_in": 500, "Rminus1_stop": 0.01,
                          "Rminus1_cl_stop": 0.2, "max_tries": "100d", "seed": 42}})
            if mode == "polychord":
                sampler = {"polychord": {"nlive": "50d", "num_repeats": "5d",
                    "precision_criterion": 0.001, "do_clustering": True,
                    "cluster_posteriors": True, "boost_posterior": 5, "seed": 42}}
            info = {"packages_path": "emulator_bridge/packages", "stop_at_error": True,
                    "theory": {"emulator_bridge.theory.SegmentedEmulator": {
                        "emulator_path": "../Emulator", "models_path": "emulator_bridge/models",
                        "device": "cpu"}}, "likelihood": likelihood,
                    "params": parameters, "sampler": sampler,
                    "output": f"emulator_bridge/chains/{dataset}_{mode}"}
            (folder / f"{dataset}_{mode}.yaml").write_text(
                "# Generated by python -m emulator_bridge.make_configs; run from the Cobaya root.\n"
                + yaml.safe_dump(info, sort_keys=False))
        # Matching fixed-nuisance comparison configuration for saved test spectra.
        compare = {"packages_path": "emulator_bridge/packages", "likelihood": likelihood,
                   "params": {key: value["ref"] for key, value in parameters.items()
                              if key not in specification}}
        (folder / f"{dataset}_compare.yaml").write_text(yaml.safe_dump(compare, sort_keys=False))


if __name__ == "__main__":
    make_configs()
